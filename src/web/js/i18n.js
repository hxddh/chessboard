  const FALLBACK = "zh-CN";
  let lang = FALLBACK;

  function available() {
    return Object.keys(DICT).map((id) => ({ id, name: DICT[id]["lang.name"] }));
  }

  function setLang(id) {
    lang = DICT[id] ? id : FALLBACK;
    return lang;
  }

  function getLang() { return lang; }

  /**
   * Best language for someone who has never set one, from the OS/browser
   * locale. Only consulted on a first run — a stored preference always wins,
   * so nobody's explicit choice can be overridden by their system settings.
   *
   * Without this, 1.6's translation work was unreachable: the app booted in
   * Chinese for everyone, including the first-run dialog that decides whether
   * a newcomer sees the course at all.
   */
  function detectLang(nav) {
    const src = nav || (typeof navigator !== "undefined" ? navigator : null);
    if (!src) return FALLBACK;
    const tags = [].concat(src.languages || [], src.language || []);
    for (const raw of tags) {
      const tag = String(raw || "").toLowerCase();
      if (!tag) continue;
      if (tag.startsWith("zh")) return "zh-CN";
      const base = tag.split("-")[0];
      if (DICT[base]) return base;
      const exact = Object.keys(DICT).find((id) => id.toLowerCase() === tag);
      if (exact) return exact;
    }
    return FALLBACK;
  }

  function t(key) {
    const table = DICT[lang] || DICT[FALLBACK];
    if (key in table) return table[key];
    const base = DICT[FALLBACK];
    return key in base ? base[key] : key;
  }

  /**
   * Translate with positional substitution: `{0}`, `{1}`, … are replaced by
   * `vals` in order. Sentences that splice in a value need this rather than
   * string concatenation — word order is not the same in every language, and
   * a concatenated "还不是将死 —— 黑方可走 " + move cannot be rendered as
   * "Not mate yet — Black escapes with " + move without hard-coding it.
   * @param {string} key
   * @param {Array} vals
   */
  function tf(key, vals) {
    const s = t(key);
    return s.replace(/\{(\d+)\}/g, (m, i) => {
      const v = vals && vals[Number(i)];
      return v === undefined || v === null ? "" : String(v);
    });
  }

  /**
   * Apply translations to every annotated node in `root`:
   * `data-i18n` → text, `data-i18n-title` → tooltip, `data-i18n-aria` →
   * aria-label. The aria pass matters as much as the visible one: an
   * untranslated aria-label is a screen-reader user hearing the wrong
   * language, which is invisible to anyone testing by eye.
   */
  function apply(root) {
    const scope = root || (typeof document !== "undefined" ? document : null);
    if (!scope) return;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
  }

  export const ChessI18n = { t, tf, apply, setLang, getLang, detectLang, available, DICT };
