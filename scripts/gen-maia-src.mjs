/**
 * Generate src/web/js/maia-<band>.js for each net in third_party/maia/: the
 * ungzipped lc0 file as base64, as window.CHESS_MAIA_<band> (13.0 H). The
 * same road engine-src.js takes — zero:// cannot fetch a packaged file, but
 * it can load a script — and like it, generated at build time and
 * gitignored; third_party/maia/ is the committed source of truth. The
 * worker decodes the text (src/web/js/human/worker.js).
 *
 * Run: node scripts/gen-maia-src.mjs
 */
import fs from "fs";
import path from "path";
import zlib from "zlib";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "third_party", "maia");
export const MAIA_BANDS = [1100, 1300, 1500, 1700, 1900];
for (const band of MAIA_BANDS) {
  const raw = zlib.gunzipSync(fs.readFileSync(path.join(dir, "maia-" + band + ".pb.gz")));
  const out = "/* generated by scripts/gen-maia-src.mjs — do not edit.\n" +
    " * Maia " + band + " (CSSLab, GPL-3.0) — see third_party/maia/. */\n" +
    "window.CHESS_MAIA_" + band + " = " + JSON.stringify(raw.toString("base64")) + ";\n";
  const dest = path.join(root, "src", "web", "js", "maia-" + band + ".js");
  fs.writeFileSync(dest, out);
  console.log("wrote", path.relative(root, dest), Math.round(out.length / 1024 / 1024 * 10) / 10 + "MB");
}
