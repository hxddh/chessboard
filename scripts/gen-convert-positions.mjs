/**
 * The won positions scripts/test-convert.mjs plays out (v20-0-plan §3 P1
 * acceptance): 50 positions where the side to move wins (Stockfish, depth
 * 14: ≥ +6, which is ≥ 90% on lichess's curve, and no mate in ≤ 5 already on
 * the board), in three kinds —
 *
 *   middlegame  26 positions from real Lichess games (scripts/fixtures/human-positions.json,
 *               1100–1900 bands), plies 16–59, with the game's own history
 *   rook        12 endings: K + R + pawns against K + pawns, the rook the difference
 *   queen       12 endings: K + Q + pawns against K + pawns
 *
 * Generated once and committed (scripts/fixtures/convert-positions.json); the
 * generator is seeded, so a re-run gives the same file.
 *
 *   node scripts/gen-convert-positions.mjs
 */
import fs from "fs";
import path from "path";
import { Chess } from "../src/app/core/chess.js";
import { ROOT } from "./lib/app-module.mjs";
import { nodeStockfish } from "./lib/sf-backend.mjs";
import { rngFrom } from "./lib/opp-game.mjs";

process.removeAllListeners("warning");
const OUT = path.join(ROOT, "scripts/fixtures/convert-positions.json");
const sf = await nodeStockfish({ hash: 64 });
const rnd = rngFrom(20261106);
const DEPTH = 14;

async function verdict(fen) {
  const g = new Chess(fen);
  if (g.game_over() || g.in_check()) return null;
  await sf.newGame();
  const r = await sf.search(fen, { multipv: 1, depth: DEPTH });
  const s = r.lines[0] && r.lines[0].score;
  if (!s) return null;
  if (s.mate !== undefined) return s.mate > 5 ? { mate: s.mate } : null;
  return s.cp >= 600 ? { cp: s.cp } : null;
}

const out = [];

// --- middlegames from real games -------------------------------------------------
const human = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts/fixtures/human-positions.json"), "utf8"));
const games = Object.values(human.bands).flat();
const order = games.map((g, i) => [rnd(), i]).sort((a, b) => a[0] - b[0]).map(([, i]) => games[i]);
let mid = 0;
for (const gm of order) {
  if (mid >= 26) break;
  const ucis = gm.moves.split(" ").concat(gm.human ? [gm.human] : []);
  const g = new Chess();
  const fens = [g.fen()];
  for (const u of ucis) { if (!g.move({ from: u.slice(0, 2), to: u.slice(2, 4), promotion: u[4] })) break; fens.push(g.fen()); }
  // the first position from ply 16 on where the side to move is winning and the board is quiet
  for (let i = 16; i < fens.length; i++) {
    const men = fens[i].split(" ")[0].replace(/[^a-zA-Z]/g, "").length;
    if (men < 14) break;
    const v = await verdict(fens[i]);
    if (!v || (v.cp !== undefined && v.cp > 2500)) continue;
    out.push({ kind: "middlegame", fen: fens[i], history: fens.slice(Math.max(0, i - 7), i), sf: v, site: gm.site });
    mid++;
    process.stdout.write("\r  middlegame " + mid);
    break;
  }
}
console.log();

// --- endings --------------------------------------------------------------------
const SQ = (f, r) => "abcdefgh"[f] + (r + 1);
function ending(extra) {
  for (;;) {
    const g = new Chess("8/8/8/8/8/8/8/8 w - - 0 1");
    g.clear();
    const used = new Set();
    const put = (type, color, rMin = 0, rMax = 7) => {
      for (let t = 0; t < 100; t++) {
        const sq = SQ(Math.floor(rnd() * 8), rMin + Math.floor(rnd() * (rMax - rMin + 1)));
        if (used.has(sq)) continue;
        used.add(sq);
        return g.put({ type, color }, sq);
      }
      return false;
    };
    put("k", "w"); put("k", "b");
    put(extra, "w");
    const pw = 1 + Math.floor(rnd() * 3), pb = 1 + Math.floor(rnd() * 3);
    for (let i = 0; i < pw; i++) put("p", "w", 1, 5);
    for (let i = 0; i < pb; i++) put("p", "b", 2, 6);
    const fen = g.fen().replace(/ [wb] .*/, " w - - 0 40");
    const c = new Chess(fen);
    if (!c.fen || c.in_check() || c.game_over()) continue;
    // the side not to move must not be in check either
    const flip = fen.replace(" w ", " b ");
    if (new Chess(flip).in_check()) continue;
    return fen;
  }
}
for (const [kind, piece, n] of [["rook", "r", 12], ["queen", "q", 12]]) {
  let k = 0;
  while (k < n) {
    const fen = ending(piece);
    const v = await verdict(fen);
    if (!v) continue;
    out.push({ kind, fen, history: [], sf: v });
    k++;
    process.stdout.write("\r  " + kind + " " + k);
  }
  console.log();
}

fs.writeFileSync(OUT, JSON.stringify({
  _: "Won positions for scripts/test-convert.mjs (generated by scripts/gen-convert-positions.mjs, seeded): the side to move wins " +
    "(Stockfish 19 lite, depth " + DEPTH + ": ≥ +600 cp or a mate in more than 5). middlegame = Lichess open database (CC0) games " +
    "from scripts/fixtures/human-positions.json with the game's last 7 positions as history; rook / queen = random endings, that piece up.",
  positions: out,
}, null, 0).replace(/\},\{"kind"/g, '},\n{"kind"') + "\n");
console.log(out.length + " positions → " + path.relative(ROOT, OUT));
process.exit(0);
