#!/usr/bin/env node
/**
 * 12.0 A: recorded samples, the day there are some.
 *
 * The wooden set is rendered (sound-bank.js says why: no recording of wooden
 * pieces could be found whose licence GPLv3 can carry and whose source could
 * be checked from the machine that made it). This is the way in for one that
 * can: put WAV files in `sounds/`, named for the event and the take —
 *
 *   sounds/move-1.wav  sounds/move-2.wav  sounds/capture-1.wav  …
 *
 * (any of sound-bank.js SOUND_NAMES; 16-bit PCM, mono or stereo, 22.05–48 kHz,
 * at most 2 s each, 300 KB in all), say where each came from and under what
 * licence in `sounds/CREDITS.md`, and run
 *
 *   node scripts/sound-kit.mjs && npm run build
 *
 * It writes src/web/js/sound-kit.js (the samples, base64 — zero:// cannot
 * fetch, so a file travels inside a chunk, chunk-sounds.js, loaded on the
 * first sound) and src/web/js/sound-kit-names.js (which events have one, so
 * nothing is loaded when none do). audio.js plays a recorded take where an
 * event has one and the rendered set everywhere else.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const KIT_BUDGET = 300 * 1024;
export const KIT_MAX_S = 2;

/** The header of a WAV file, or an Error saying what is wrong with it. */
export function parseWav(buf) {
  const b = Buffer.from(buf);
  if (b.length < 44 || b.toString("ascii", 0, 4) !== "RIFF" || b.toString("ascii", 8, 12) !== "WAVE") return new Error("not a WAV file");
  let at = 12, fmt = null, data = null;
  while (at + 8 <= b.length) {
    const id = b.toString("ascii", at, at + 4), size = b.readUInt32LE(at + 4);
    if (id === "fmt ") fmt = { format: b.readUInt16LE(at + 8), channels: b.readUInt16LE(at + 10), rate: b.readUInt32LE(at + 12), bits: b.readUInt16LE(at + 22) };
    if (id === "data") data = size;
    at += 8 + size + (size & 1);
  }
  if (!fmt || data == null) return new Error("no fmt or data chunk");
  if (fmt.format !== 1 || fmt.bits !== 16) return new Error("not 16-bit PCM");
  if (fmt.channels < 1 || fmt.channels > 2) return new Error(fmt.channels + " channels");
  if (fmt.rate < 22050 || fmt.rate > 48000) return new Error(fmt.rate + " Hz");
  const seconds = data / (fmt.rate * fmt.channels * 2);
  if (seconds > KIT_MAX_S) return new Error(seconds.toFixed(2) + " s (at most " + KIT_MAX_S + ")");
  return { ...fmt, seconds };
}

/**
 * The kit from a list of {file, bytes}: { kit: {name: [base64, …]}, names, bytes }.
 * Throws on a file it cannot take — a wrong name, a bad WAV, the budget.
 */
export function packKit(files, soundNames) {
  const kit = {};
  let bytes = 0;
  for (const { file, bytes: data } of [...files].sort((a, z) => a.file.localeCompare(z.file))) {
    const m = /^([a-z]+)-(\d+)\.wav$/.exec(file);
    if (!m || !soundNames.includes(m[1])) throw new Error(file + ": name it <event>-<n>.wav, the event one of " + soundNames.join(", "));
    const w = parseWav(data);
    if (w instanceof Error) throw new Error(file + ": " + w.message);
    bytes += data.length;
    (kit[m[1]] = kit[m[1]] || []).push(Buffer.from(data).toString("base64"));
  }
  if (bytes > KIT_BUDGET) throw new Error("the kit is " + bytes + " bytes; the budget is " + KIT_BUDGET);
  return { kit, names: Object.keys(kit).sort(), bytes };
}

/** The two generated modules' text. */
export function kitModules({ kit, names }) {
  const head = "// generated by scripts/sound-kit.mjs from sounds/*.wav — do not edit\n";
  return {
    kit: head + "export const SOUND_KIT = " + JSON.stringify(kit) + ";\n",
    names: head + "export const KIT_NAMES = " + JSON.stringify(names) + ";\n",
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const dir = path.join(root, "sounds");
  const files = (fs.existsSync(dir) ? fs.readdirSync(dir) : []).filter((f) => f.endsWith(".wav"))
    .map((file) => ({ file, bytes: fs.readFileSync(path.join(dir, file)) }));
  const src = fs.readFileSync(path.join(root, "src/web/js/sound-bank.js"), "utf8");
  const names = JSON.parse(/export const SOUND_NAMES = (\[[^\]]*\])/.exec(src)[1].replace(/\s+/g, " ").replace(/'/g, '"'));
  const packed = packKit(files, names);
  const mods = kitModules(packed);
  fs.writeFileSync(path.join(root, "src/web/js/sound-kit.js"), mods.kit);
  fs.writeFileSync(path.join(root, "src/web/js/sound-kit-names.js"), mods.names);
  console.log(packed.names.length ? "sound kit: " + packed.names.map((n) => n + "×" + packed.kit[n].length).join(", ") + " — " + packed.bytes + " bytes"
    : "sound kit: empty (no sounds/*.wav) — the rendered set plays");
}
